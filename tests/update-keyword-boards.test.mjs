import assert from 'node:assert/strict';
import {MEDIA,mergeMedia,updateCutoff,monitorCutoff} from '../scripts/update-data.mjs';
import {refreshTaxonomy} from '../scripts/refresh-taxonomy.mjs';
import {classifyBoards,KEYWORD_RULE_VERSION} from '../lib/keyword-boards.js';
import {panelCell} from '../lib/panel.js';
const now=new Date('2026-10-09T07:00:00Z');
assert.equal(updateCutoff('2026-10-08',undefined,now),'2026-10-08','Partial saved snapshot must never roll back');
assert.equal(updateCutoff('2026-09-20',undefined,now),'2026-10-04');
assert.equal(updateCutoff('2026-10-08',undefined,new Date('2026-10-12T01:00:00Z')),'2026-10-11');
assert.throws(()=>updateCutoff('2026-10-08','2026-10-04',now));
assert.throws(()=>updateCutoff('2026-10-08','2026-10-11',now));
assert.equal(monitorCutoff('2026-10-08'),'2026-10-04');
assert.equal(monitorCutoff('2026-10-11'),'2026-10-11');
const rows=MEDIA.map((source_id,i)=>({id:String(i),source_id,title:'服务器液冷部署',date:'2026-10-01',month:'2026-10',url:'https://example.org/'+i,categories:['liquid_cooling'],tags:[],application_reviewed:true,keyword_context_class:'application',board_matches:{business:[],components:['components_liquid_cooling'],scenarios:[]},keyword_rule_version:KEYWORD_RULE_VERSION}));
const original={window:{start:'2026-10-01',end:'2026-10-08'},sources:MEDIA.map(id=>({id,kind:'news',group:'media',coverage:[{month:'2026-10',status:'complete',covered_through:'2026-10-08',keyword_application_reviewed:true,application_reviewed:true}]})),documents:rows};
const incoming=structuredClone(rows);incoming[0].title='服务器GPU集群上线';
const fresh={cutoff:'2026-10-08',scanned_through:'2026-10-08',reread_start:'2026-10-01',checked_at:'2026-10-09T07:00:00Z',sources:MEDIA.map(source_id=>({source_id,rows:1,complete:true})),documents:incoming};
const {panel}=mergeMedia(original,fresh),changed=panel.documents[0];
assert.deepEqual(changed.board_matches.components,['components_accelerators'],'Corrected title discards stale board matches');
assert.equal(changed.keyword_context_class,'other');
assert.equal(panel.sources[0].coverage[0].keyword_application_reviewed,false);
assert.equal(panel.sources[1].coverage[0].keyword_application_reviewed,true,'Unchanged reviewed month remains reviewed');
const period={id:'2026-10',months:['2026-10']};
assert.equal(panelCell(panel,panel.sources[0],'components_accelerators','application',period).value,null);
assert.equal(panelCell(panel,panel.sources[1],'components_liquid_cooling','application',period).value,1000);
// Importing the transformation is side-effect free; it never rewrites research data.
const research={events:[{id:'research',title:'液冷服务器',categories:['liquid_cooling']}],leads:[]},before=JSON.stringify(research);
const transformed=refreshTaxonomy(panel,research,{},'2026-10-09');
assert.equal(transformed.panel.taxonomy.version,KEYWORD_RULE_VERSION);
assert.equal(transformed.panel.taxonomy.boards.length,3);
assert.equal(transformed.panel.taxonomy.legacy.groups.length,5);
assert.equal(transformed.sources.taxonomy.version,KEYWORD_RULE_VERSION);
assert.equal(transformed.review.version,KEYWORD_RULE_VERSION);
assert.equal(JSON.stringify(research),before);
for(const r of panel.documents)assert.deepEqual(r.board_matches.components,classifyBoards(r,'news').components);
console.log('PASS: partial snapshot cutoffs, completed-week monitor, refreshed keyword projections, review invalidation and safe taxonomy imports');
