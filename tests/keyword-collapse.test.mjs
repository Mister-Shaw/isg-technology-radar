import assert from 'node:assert/strict';
import {rowsForBoard} from '../lib/keyword-boards.js';
import {defaultCollapsedKeywordParents,collapsibleParents,keywordRowVisible,toggleKeywordParent,setKeywordParentsCollapsed} from '../lib/keyword-collapse.js';
const business=rowsForBoard('business'),components=rowsForBoard('components'),scenarios=rowsForBoard('scenarios');
const ids=rows=>rows.map(r=>r.id),visible=(rows,s)=>rows.filter(r=>keywordRowVisible(r.id,s));
const parents=collapsibleParents(ids(business));
assert.equal(parents.length,4);
assert.equal(collapsibleParents(ids(components)).length,9);
assert.deepEqual(collapsibleParents(ids(scenarios)),[]);
const initial=new Set(),one=toggleKeywordParent(initial,parents[0]);
assert.equal(initial.size,0,'State updates must not mutate the previous state');
assert(visible(business,one).every(r=>r.parentId!==parents[0]));
assert(visible(business,one).some(r=>r.id===parents[0]));
const folded=setKeywordParentsCollapsed(one,parents,true);
assert.equal(visible(business,folded).length,4);
assert.equal(visible(components,folded).length,36,'Each board keeps independent folds');
assert.equal(visible(scenarios,folded).length,8);
const other=setKeywordParentsCollapsed(folded,collapsibleParents(ids(components)),true);
assert.equal(visible(components,other).length,9);
const expanded=setKeywordParentsCollapsed(other,parents,false);
assert.equal(visible(business,expanded).length,29);
assert.equal(visible(components,expanded).length,9);
assert.equal(visible(business,toggleKeywordParent(one,parents[0])).length,29);
assert(keywordRowVisible('all',folded));
console.log('PASS: individual and all folding, immutable state, board isolation, single-level board preserved');

const defaults=defaultCollapsedKeywordParents();
assert.equal(visible(business,defaults).length,4);
assert.equal(visible(components,defaults).length,9);
assert.equal(visible(scenarios,defaults).length,8);
assert.equal(defaults.size,13);
assert.equal(visible(business,setKeywordParentsCollapsed(defaults,parents,false)).length,29);
console.log("PASS: every hierarchical board defaults folded and can reopen");
